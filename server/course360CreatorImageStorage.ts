import { TRPCError } from "@trpc/server";
import { mkdtemp, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ENV } from "./_core/env";
import { storeStudioFile, resolveStudioStorage, assertStudioRegistrationUrl, requestStudioStorage } from "./lib/course360StudioStorage";
import { verifyCreatorImageBytes, type CreatorVerifiedImage } from "./course360CreatorImageBytes";
export function creatorImageStorageStatus() {
  const aws = !!(process.env.AWS_ACCESS_KEY_ID && process.env.AWS_SECRET_ACCESS_KEY && process.env.AWS_REGION && process.env.AWS_S3_BUCKET);
  if (aws) return true;
  if (!ENV.forgeApiUrl || !ENV.forgeApiKey) return false;
  try { const u = new URL(ENV.forgeApiUrl); return u.protocol === "https:" && !u.username && !u.password && !u.search && !u.hash && (!u.port || u.port === "443"); } catch { return false; }
}
function fail(message: string): never { throw new TRPCError({ code: "PRECONDITION_FAILED", message }); }
/** Never takes a caller/provider URL. New random key, own temporary file, and exact stored-byte verification. */
export async function saveCreatorOwnedImageBytes(orgId: number, key: string, image: CreatorVerifiedImage, signal: AbortSignal) {
  if (!Number.isSafeInteger(orgId) || orgId < 1 || !new RegExp(`^org-${orgId}/media/creator-images/[a-f0-9-]{36}\\.png$`).test(key)) fail("A new exact-school Creator image key is required.");
  verifyCreatorImageBytes(image.bytes, image.mimeType);
  if (!creatorImageStorageStatus()) fail("Abortable owned image storage is not configured for HTTPS.");
  signal.throwIfAborted();
  const directory = await mkdtemp(join(tmpdir(), "course360-creator-image-"));
  try {
    const path = join(directory, "new.png"); await writeFile(path, image.bytes, { flag: "wx", mode: 0o600 }); signal.throwIfAborted();
    const stored = await storeStudioFile(key, path, image.mimeType, signal); signal.throwIfAborted();
    if (stored.key !== key) fail("Storage returned a different owned image key.");
    const resolved = await resolveStudioStorage(key, signal); signal.throwIfAborted();
    if (resolved.key !== key) fail("Resolved storage key differs from the generated image.");
    assertStudioRegistrationUrl(stored.url, key, resolved.url);
    const response = await requestStudioStorage(resolved.url, "GET", signal);
    const declared = String(response.headers["content-length"] ?? ""), type = String(response.headers["content-type"] ?? "").split(";")[0].trim().toLowerCase();
    if (!/^\d+$/.test(declared) || Number(declared) !== image.bytes.length || type !== image.mimeType) { response.destroy(); fail("Stored image MIME/byte receipt differs from generated bytes."); }
    let count = 0; const parts: Buffer[] = []; const abort = () => response.destroy(); signal.addEventListener("abort", abort, { once: true });
    try {
      for await (const chunk of response) { signal.throwIfAborted(); count += chunk.length; if (count > image.bytes.length) fail("Stored image exceeds its byte receipt."); parts.push(Buffer.from(chunk)); }
      signal.throwIfAborted();
      if (count !== image.bytes.length || !Buffer.concat(parts).equals(image.bytes)) fail("Stored image bytes do not match the actual generated image.");
    } finally { signal.removeEventListener("abort", abort); response.destroy(); }
    let url = stored.url;
    if (!url.startsWith("/manus-storage/")) { const u = new URL(url); if (decodeURIComponent(u.pathname).endsWith(`/${key}`)) u.search = ""; url = u.toString(); }
    return { key, url, size: count, mimeType: image.mimeType };
  } finally { await rm(directory, { recursive: true, force: true }); }
}
