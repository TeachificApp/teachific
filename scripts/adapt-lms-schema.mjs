#!/usr/bin/env node
/**
 * LMS Schema Adaptation Script
 * 
 * Extracts LMS tables from the imported module and adapts them for:
 * 1. Org-level scoping (add orgId where missing)
 * 2. Custom domain support (add fields to course table)
 * 3. Removes Thinkific-specific tables (cmeCoursesCache, cmeCourseMeta, cmeEnrollmentCache)
 * 4. Removes cross-domain logic
 */

import fs from 'fs';
import path from 'path';

const LMS_SCHEMA_PATH = '/home/ubuntu/upload/teachific-modules/lms/schema/schema.ts';
const OUTPUT_PATH = '/home/ubuntu/scorm-host/drizzle/lms-schema-adapted.ts';

// Tables to remove (Thinkific-specific, not needed for Teachific)
const TABLES_TO_REMOVE = [
  'cmeCoursesCache',
  'cmeCourseMeta',
  'cmeEnrollmentCache',
  'lmsThinkificImports',
  'lmsArchive', // Archive functionality can be added later
];

// Tables that need orgId added
const TABLES_NEEDING_ORG_ID = [
  'lmsCourses',
  'lmsSections',
  'lmsLessons',
  'lmsQuizzes',
  'lmsQuizQuestions',
  'lmsEnrollments',
  'lmsLessonProgress',
  'lmsGroups',
  'lmsGroupCourses',
  'lmsGroupSeats',
  'lmsInstructors',
  'lmsCourseInstructors',
  'lmsAffiliates',
  'lmsAffiliateConversions',
  'lmsLandingPages',
  'lmsOrders',
  'lmsPageTemplates',
  'lmsCertificateTemplates',
  'lmsCertificates',
  'lmsLessonNotes',
  'lmsLessonBookmarks',
  'lmsCollections',
  'lmsCollectionCourses',
  'lmsVideoEvents',
  'lmsQuizAttempts',
  'lmsPricingOptions',
  'lmsPendingEnrollments',
  'lessonComments',
  'lessonTemplates',
  'lmsCohortSessions',
  'lmsCohortAssignments',
  'lmsCohortRecordings',
  'lmsCohortSubmissions',
  'lmsCohortGroups',
  'lmsCohortGroupEnrollments',
  'lmsCohortMessages',
  'lmsCohortStaff',
  'lmsInterests',
  'instructorCoursePermissions',
  'instructorPublishRequests',
  'instructorPayoutConfig',
];

// Tables that need custom domain fields
const TABLES_NEEDING_CUSTOM_DOMAIN = [
  'lmsCourses',
  'lmsLandingPages',
];

console.log('📖 Reading LMS schema...');
let content = fs.readFileSync(LMS_SCHEMA_PATH, 'utf-8');

// Remove import statements (we'll add our own)
content = content.replace(/^import\s*{[\s\S]*?}\s*from\s*["']drizzle-orm\/mysql-core["'];?/m, '');

// Split into table definitions
const tableMatches = [...content.matchAll(/export const (\w+) = mysqlTable\([^;]+\);[\s\S]*?export type Insert\w+ = typeof \w+\.\$inferInsert;/g)];

console.log(`✅ Found ${tableMatches.length} table definitions`);

let adaptedTables = [];
let removedCount = 0;
let adaptedCount = 0;

for (const match of tableMatches) {
  const tableName = match[1];
  const tableDefinition = match[0];
  
  // Skip tables to remove
  if (TABLES_TO_REMOVE.includes(tableName)) {
    console.log(`⏭️  Skipping: ${tableName} (Thinkific-specific)`);
    removedCount++;
    continue;
  }
  
  let adapted = tableDefinition;
  
  // Add orgId to tables that need it
  if (TABLES_NEEDING_ORG_ID.includes(tableName)) {
    // Find the first field and add orgId after it
    adapted = adapted.replace(
      /mysqlTable\("[\w_]+",\s*{/,
      (match) => {
        return match + '\n  orgId: int("orgId").notNull(),';
      }
    );
  }
  
  // Add custom domain fields to course and landing page tables
  if (TABLES_NEEDING_CUSTOM_DOMAIN.includes(tableName)) {
    // Add before createdAt
    adapted = adapted.replace(
      /(  \w+: .*?\.notNull\(\),\s*)(createdAt:)/,
      `$1customDomain: varchar("customDomain", { length: 255 }),
  customDomainVerified: boolean("customDomainVerified").default(false).notNull(),
  customDomainVerificationToken: varchar("customDomainVerificationToken", { length: 128 }),
  customDomainVerificationStatus: mysqlEnum("customDomainVerificationStatus", ["unverified", "pending", "verified"]).default("unverified").notNull(),
  $2`
    );
  }
  
  adaptedTables.push(adapted);
  adaptedCount++;
}

console.log(`\n📊 Summary:`);
console.log(`  ✅ Adapted: ${adaptedCount} tables`);
console.log(`  ⏭️  Removed: ${removedCount} tables`);
console.log(`  📝 Total: ${adaptedCount + removedCount} tables`);

// Write adapted schema
const output = `// ─── LMS Module (Adapted for Teachific) ───────────────────────────────────────
// This file contains all 47 LMS tables adapted for org-level scoping and custom domains.
// Generated by: adapt-lms-schema.mjs

import {
  boolean,
  decimal,
  int,
  json,
  longtext,
  mysqlEnum,
  mysqlTable,
  text,
  timestamp,
  varchar,
  bigint,
  uniqueIndex,
} from "drizzle-orm/mysql-core";

${adaptedTables.join('\n\n')}
`;

fs.writeFileSync(OUTPUT_PATH, output);
console.log(`\n✨ Adapted schema written to: ${OUTPUT_PATH}`);
console.log(`📏 File size: ${(output.length / 1024).toFixed(1)} KB`);
