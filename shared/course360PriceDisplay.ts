/** Format canonical Course360 dollar amounts for UI only; never converts minor-unit API values. */
export function formatCourse360Dollars(dollars: number): string {
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(dollars);
}
